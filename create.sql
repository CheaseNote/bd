BEGIN;

-- E1 Пользователь
CREATE TABLE public.users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) NOT NULL,
    birth_date DATE NULL,
    login VARCHAR(64) NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    phone_number VARCHAR(32) NOT NULL,
    is_premium BOOLEAN DEFAULT FALSE NOT NULL
);

-- E2 Музыкальная карта
CREATE TABLE public.musical_maps (
    map_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    formed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    listening_frequency NUMERIC(12,4) NULL CHECK (listening_frequency >= 0),
    app_activity NUMERIC(12,4) NULL CHECK (app_activity >= 0),
    mood VARCHAR(64) NULL,
    UNIQUE (user_id, formed_at)
);

-- E3 Плейлист
CREATE TABLE public.playlists (
    playlist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    title VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- E4 Музыкальный исполнитель
CREATE TABLE public.artists (
    artist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname VARCHAR(128) NOT NULL,
    description TEXT NULL
);

-- E5 Музыкальный жанр
CREATE TABLE public.genres (
    genre_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(128) NOT NULL UNIQUE,
    description TEXT NULL,
    popularity NUMERIC(12,4) NULL CHECK (popularity >= 0)
);

-- E6 Альбом
CREATE TABLE public.albums (
    album_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    artist_id BIGINT NOT NULL REFERENCES public.artists (artist_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    genre_id BIGINT NOT NULL REFERENCES public.genres (genre_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    title VARCHAR(255) NOT NULL,
    release_year SMALLINT NULL,
    song_count INTEGER DEFAULT 0 NOT NULL CHECK (song_count >= 0)
);

-- E7 Песня
CREATE TABLE public.songs (
    song_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uploaded_by_user_id BIGINT NULL REFERENCES public.users (user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    uploaded_at TIMESTAMPTZ NULL,
    artist_id BIGINT NOT NULL REFERENCES public.artists (artist_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    album_id BIGINT NULL REFERENCES public.albums (album_id)
        ON UPDATE CASCADE ON DELETE SET NULL,
    title VARCHAR(255) NOT NULL,
    lyrics TEXT NULL,
    duration_seconds INTEGER NOT NULL CHECK (duration_seconds > 0),
    rating NUMERIC(4,2) NULL CHECK (rating BETWEEN 1 AND 10),
    CHECK ((uploaded_by_user_id IS NULL) = (uploaded_at IS NULL))
);

-- E8 Оценка
CREATE TABLE public.ratings (
    rating_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    song_id BIGINT NOT NULL REFERENCES public.songs (song_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    score SMALLINT NOT NULL CHECK (score BETWEEN 1 AND 10),
    rated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UNIQUE (user_id, song_id)
);

-- E9 Комментарий
CREATE TABLE public.comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    song_id BIGINT NOT NULL REFERENCES public.songs (song_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    body TEXT NOT NULL,
    published_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- E10 Прослушивание
CREATE TABLE public.listenings (
    listening_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    song_id BIGINT NOT NULL REFERENCES public.songs (song_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    playlist_id BIGINT NULL REFERENCES public.playlists (playlist_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    started_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    actual_duration_seconds NUMERIC(12,3) NOT NULL CHECK (actual_duration_seconds >= 0),
    launch_source VARCHAR(32) NOT NULL
        CHECK (launch_source IN ('search', 'recommendation', 'playlist', 'subscription')),
    playback_context TEXT NOT NULL,
    CHECK ((launch_source = 'playlist') = (playlist_id IS NOT NULL))
);

-- E11 Действие пользователя
CREATE TABLE public.user_actions (
    action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users (user_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    category SMALLINT NOT NULL CHECK (category BETWEEN 1 AND 9),
    action_type VARCHAR(64) NOT NULL,
    performed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- E12 Подписка на исполнителя
CREATE TABLE public.artist_subscriptions (
    user_id BIGINT NOT NULL REFERENCES public.users (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    artist_id BIGINT NOT NULL REFERENCES public.artists (artist_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    subscribed_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP NOT NULL,
    PRIMARY KEY (user_id, artist_id)
);

-- E13 Исполнитель музыкальной карты
CREATE TABLE public.map_artists (
    map_id BIGINT NOT NULL REFERENCES public.musical_maps (map_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    artist_id BIGINT NOT NULL REFERENCES public.artists (artist_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    top_position INTEGER NULL CHECK (top_position > 0),
    PRIMARY KEY (map_id, artist_id),
    UNIQUE (map_id, top_position)
);

-- E14 Жанр музыкальной карты
CREATE TABLE public.map_genres (
    map_id BIGINT NOT NULL REFERENCES public.musical_maps (map_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    genre_id BIGINT NOT NULL REFERENCES public.genres (genre_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    top_position INTEGER NULL CHECK (top_position > 0),
    PRIMARY KEY (map_id, genre_id),
    UNIQUE (map_id, top_position)
);

-- E15 Песня музыкальной карты
CREATE TABLE public.map_songs (
    map_id BIGINT NOT NULL REFERENCES public.musical_maps (map_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    song_id BIGINT NOT NULL REFERENCES public.songs (song_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    top_position INTEGER NULL CHECK (top_position > 0),
    last_listened_at TIMESTAMPTZ NULL,
    PRIMARY KEY (map_id, song_id),
    UNIQUE (map_id, top_position)
);

-- E16 Песня плейлиста
CREATE TABLE public.playlist_songs (
    playlist_id BIGINT NOT NULL REFERENCES public.playlists (playlist_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    song_id BIGINT NOT NULL REFERENCES public.songs (song_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    PRIMARY KEY (playlist_id, song_id)
);

-- E17 Жанр песни
CREATE TABLE public.song_genres (
    genre_id BIGINT NOT NULL REFERENCES public.genres (genre_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    song_id BIGINT NOT NULL REFERENCES public.songs (song_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    PRIMARY KEY (genre_id, song_id)
);

-- E18 Действие с музыкальной картой
CREATE TABLE public.map_actions (
    action_id BIGINT PRIMARY KEY REFERENCES public.user_actions (action_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    map_id BIGINT NOT NULL REFERENCES public.musical_maps (map_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- E19 Действие с плейлистом
CREATE TABLE public.playlist_actions (
    action_id BIGINT PRIMARY KEY REFERENCES public.user_actions (action_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    playlist_id BIGINT NOT NULL REFERENCES public.playlists (playlist_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- E20 Действие с исполнителем
CREATE TABLE public.artist_actions (
    action_id BIGINT PRIMARY KEY REFERENCES public.user_actions (action_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    artist_id BIGINT NOT NULL REFERENCES public.artists (artist_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- E21 Действие с жанром
CREATE TABLE public.genre_actions (
    action_id BIGINT PRIMARY KEY REFERENCES public.user_actions (action_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    genre_id BIGINT NOT NULL REFERENCES public.genres (genre_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- E22 Действие с альбомом
CREATE TABLE public.album_actions (
    action_id BIGINT PRIMARY KEY REFERENCES public.user_actions (action_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    album_id BIGINT NOT NULL REFERENCES public.albums (album_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- E23 Действие с песней
CREATE TABLE public.song_actions (
    action_id BIGINT PRIMARY KEY REFERENCES public.user_actions (action_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    song_id BIGINT NOT NULL REFERENCES public.songs (song_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- E24 Действие с оценкой
CREATE TABLE public.rating_actions (
    action_id BIGINT PRIMARY KEY REFERENCES public.user_actions (action_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    rating_id BIGINT NOT NULL REFERENCES public.ratings (rating_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- E25 Действие с комментарием
CREATE TABLE public.comment_actions (
    action_id BIGINT PRIMARY KEY REFERENCES public.user_actions (action_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    comment_id BIGINT NOT NULL REFERENCES public.comments (comment_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- E26 Действие с прослушиванием
CREATE TABLE public.listening_actions (
    action_id BIGINT PRIMARY KEY REFERENCES public.user_actions (action_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    listening_id BIGINT NOT NULL REFERENCES public.listenings (listening_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- E27 Реакция пользователя на песню: 1 — лайк, -1 — дизлайк.
CREATE TABLE public.song_reactions (
    user_id BIGINT NOT NULL REFERENCES public.users (user_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    song_id BIGINT NOT NULL REFERENCES public.songs (song_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    reaction SMALLINT NOT NULL CHECK (reaction IN (-1, 1)),
    PRIMARY KEY (user_id, song_id)
);


COMMIT;
